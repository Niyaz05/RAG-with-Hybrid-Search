"""
DAY 5 — PART C: /auth routes
===============================
POST /auth/register - create a user (always role="student" - see db.py's
                       note on why self-service admin signup is disallowed)
POST /auth/login     - verify credentials, issue a JWT
"""

# pyrefly: ignore [missing-import]
from fastapi import APIRouter, Depends, HTTPException, status
# pyrefly: ignore [missing-import]
from fastapi.security import OAuth2PasswordRequestForm
# pyrefly: ignore [missing-import]
from sqlmodel import Session, select

from auth import create_access_token, hash_password, verify_password
from db import User, get_session

router = APIRouter(prefix="/auth", tags=["auth"])


@router.post("/register", status_code=status.HTTP_201_CREATED)
def register(email: str, password: str, session: Session = Depends(get_session)):
    existing = session.exec(select(User).where(User.email == email)).first()
    if existing:
        raise HTTPException(status_code=400, detail="Email already registered")

    user = User(email=email, hashed_password=hash_password(password))  # role defaults to "student"
    session.add(user)
    session.commit()
    session.refresh(user)  # populates user.id, generated by the database on insert
    return {"id": user.id, "email": user.email, "role": user.role}


@router.post("/login")
def login(form_data: OAuth2PasswordRequestForm = Depends(), session: Session = Depends(get_session)):
    """
    LEARNING NOTE: OAuth2PasswordRequestForm expects standard form fields
    named `username` and `password` (that's the OAuth2 spec's naming, even
    though we're using it for an email-based login) - this is what makes
    the automatic /docs "Authorize" button work out of the box.
    """
    user = session.exec(select(User).where(User.email == form_data.username)).first()
    if not user or not verify_password(form_data.password, user.hashed_password):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Incorrect email or password",
            headers={"WWW-Authenticate": "Bearer"},
        )

    token = create_access_token(data={"sub": user.email, "role": user.role})
    return {"access_token": token, "token_type": "bearer"}